/** Fills {circle} {n} {zone}... at render time. */
export const fill = (t: string, o: Record<string, string | number | null | undefined> = {}): string => String(t).replace(/\{(\w+)\}/g, (_, k: string) => String(o[k] ?? ""));

const cache = new Map<Gender, Content>();
export type Content = ReturnType<typeof build>;

/** Every text of the game in one gender. Cached per gender. */
export function buildContent(gender: Gender): Content {
  let c = cache.get(gender);
  if (!c) {
    c = build(gender);
    cache.set(gender, c);
  }
  return c;
}

